LimitNOFILE=64
MemoryMax=64M
UMask=0077

[Install]
WantedBy=multi-user.target
AIAUNIT

        persistent_ips=$(_tpmp_dns_ips "$aia_host" <<<"$persistent_xml") || return 1
        if [[ -n "$persistent_ips" && "$persistent_ips" != "$aia_gateway" ]]; then
            _tpmp_warn "${aia_host} already has a conflicting persistent libvirt DNS mapping: ${persistent_ips//$'\n'/,}"
            return 1
        fi
        if [[ -z "$persistent_ips" ]]; then
            $ROOT_ESC virsh -c qemu:///system net-update default add dns-host \
                "<host ip='${aia_gateway}'><hostname>${aia_host}</hostname></host>" \
                --config || return 1
        fi
        persistent_xml=$($ROOT_ESC virsh -c qemu:///system net-dumpxml default --inactive) || return 1
        [[ "$(_tpmp_dns_ips "$aia_host" <<<"$persistent_xml")" == "$aia_gateway" ]] || {
            _tpmp_warn "persistent ${aia_host} DNS mapping did not validate after net-update"
            return 1
        }

        if $ROOT_ESC virsh -c qemu:///system net-list --name | grep -Fxq default; then
            live_xml=$($ROOT_ESC virsh -c qemu:///system net-dumpxml default) || return 1
            live_ips=$(_tpmp_dns_ips "$aia_host" <<<"$live_xml") || return 1
            if [[ -n "$live_ips" && "$live_ips" != "$aia_gateway" ]]; then
                _tpmp_warn "${aia_host} already has a conflicting live libvirt DNS mapping: ${live_ips//$'\n'/,}"
                return 1
            fi
            if [[ -z "$live_ips" ]]; then
                $ROOT_ESC virsh -c qemu:///system net-update default add dns-host \
                    "<host ip='${aia_gateway}'><hostname>${aia_host}</hostname></host>" \
                    --live || return 1
            fi
            live_xml=$($ROOT_ESC virsh -c qemu:///system net-dumpxml default) || return 1
            [[ "$(_tpmp_dns_ips "$aia_host" <<<"$live_xml")" == "$aia_gateway" ]] || {
                _tpmp_warn "live ${aia_host} DNS mapping did not validate after net-update"
                return 1
            }
        fi

        $ROOT_ESC systemctl daemon-reload || return 1
        $ROOT_ESC systemctl enable swtpm-patch-tpm-aia.service >/dev/null || return 1
        $ROOT_ESC systemctl restart swtpm-patch-tpm-aia.service || return 1
        $ROOT_ESC systemctl is-active --quiet swtpm-patch-tpm-aia.service || return 1
        if ! python3 - "$aia_gateway" "$aia_port" "$aia_route" "$aia_certificate" "$aia_host" <<'VERIFY_AIA'
