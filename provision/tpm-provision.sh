#!/usr/bin/env bash

# source this file, then call provision_swtpm_patch_identity <amd|intel>

: "${ROOT_ESC:=sudo}"
_tpmp_info() { if declare -f fmtr::info  >/dev/null 2>&1; then fmtr::info  "$*"; else echo "[i] $*"; fi; }
_tpmp_warn() { if declare -f fmtr::warn  >/dev/null 2>&1; then fmtr::warn  "$*"; else echo "[!] $*" >&2; fi; }
_tpmp_dns_ips() {
    local hostname=$1
    python3 -c '
import sys, xml.etree.ElementTree as ET
hostname = sys.argv[1].lower().rstrip(".")
root = ET.fromstring(sys.stdin.read())
seen = set()
for host in root.findall("./dns/host"):
    names = [(node.text or "").lower().rstrip(".") for node in host.findall("./hostname")]
    address = host.get("ip", "")
    if hostname in names and address not in seen:
        seen.add(address)
        print(address)
' "$hostname"
}

provision_swtpm_patch_identity() {
    local vendor="${1:-amd}"
    local source_dir
    source_dir=$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")
    local patcher="${LIBTPMS_PATCHER:-}"
    if [[ -z "$patcher" || ! -f "$patcher" ]]; then
        patcher="/opt/swtpm-toolkit/vm-build/modules/patch_libtpms.py"
        [[ -f "$patcher" ]] || patcher="$(dirname -- "${BASH_SOURCE[0]}")/patch_libtpms.py"
    fi

 local mfr_id tpm_model tpm_version ca_subject pcr_banks tpm_profile
    local reissuer_source="${TPM_EK_REISSUER_SOURCE:-${source_dir}/../libexec/swtpm-patch-reissue-ek-cert.py}"
    local aia_server_source="${TPM_AIA_SERVER_SOURCE:-${source_dir}/../libexec/swtpm-patch-tpm-aia-server.py}"
    local reissuer_install=/usr/local/libexec/swtpm-patch-reissue-ek-cert.py
    local aia_server_install=/usr/local/libexec/swtpm-patch-tpm-aia-server.py
    local aia_host=ftpm.amd.com
    local aia_port=8080
    local aia_route=/pki/aia/amd-ftpm-ca.cer
    local aia_uri="http://${aia_host}:${aia_port}${aia_route}"
    case "$vendor" in
        intel) mfr_id="id:494E5443"; tpm_model="TGL"; tpm_version="id:02580007"
               ca_subject="/CN=CSME TGL PTT  01SVN"; pcr_banks="sha256"
 tpm_profile='{"Name":"custom","StateFormatLevel":7,"Algorithms":"rsa,rsa-min-size=2048,sha1,hmac,aes,aes-min-size=128,mgf1,keyedhash,xor,sha256,sha384,null,rsassa,rsaes,rsapss,oaep,ecdsa,ecdh,ecdaa,ecschnorr,kdf1-sp800-56a,kdf1-sp800-108,kdf2,ecc,ecc-min-size=256,ecc-nist,symcipher,cmac,ctr,ofb,cbc,cfb,ecb","Commands":"0x11f-0x122,0x124,0x126-0x12b,0x12e,0x130-0x132,0x134-0x13f,0x142-0x151,0x153-0x159,0x15b-0x15e,0x160-0x165,0x167-0x174,0x176-0x178,0x17a-0x182,0x184-0x186,0x188-0x193"}' ;;
        amd|*) vendor="amd"; mfr_id="id:414D4400"; tpm_model="AMD"; tpm_version="id:00060300"
               ca_subject="/O=Advanced Micro Devices/CN=AMD fTPM CA"; pcr_banks="sha1,sha256"
               tpm_profile='{"Name": "default-v1"}' ;;
    esac

    if [[ "$vendor" == amd ]]; then
        if [[ ! -s "$reissuer_source" || ! -s "$aia_server_source" ]]; then
            _tpmp_warn "AMD EK AIA helpers are missing beside tpm-provision.sh"
            return 1
        fi
        if ! python3 -c 'import cryptography' >/dev/null 2>&1; then
            _tpmp_warn "python cryptography module is required for AMD EK certificate provisioning"
            return 1
        fi
        $ROOT_ESC install -Dm755 "$reissuer_source" "$reissuer_install" || return 1
        $ROOT_ESC install -Dm755 "$aia_server_source" "$aia_server_install" || return 1
    fi

    _tpmp_info "Provisioning ${vendor^^} swtpm identity (manufacturer + vendor string + EK cert + PCR banks)"

 # 1) libtpms patch
    if [[ -f "$patcher" ]]; then
        if ! $ROOT_ESC python3 "$patcher" --vendor "$vendor" --verify-only >/dev/null 2>&1; then
            _tpmp_info "Patching libtpms -> ${vendor^^} (manufacturer / vendor string / firmware)"
            if ! $ROOT_ESC python3 "$patcher" --vendor "$vendor"; then
                _tpmp_warn "patch_libtpms.py returned non-zero"
                return 1
            fi
            $ROOT_ESC ldconfig || return 1
            if ! $ROOT_ESC python3 "$patcher" --vendor "$vendor" --verify-only >/dev/null 2>&1; then
                _tpmp_warn "libtpms identity verification failed after patching"
                return 1
            fi
        else
            _tpmp_info "libtpms already ${vendor^^} (manufacturer + vendor string + firmware)"
        fi
    else
        _tpmp_warn "patch_libtpms.py not found ($patcher)"
        return 1
    fi

    local wrapper=/usr/local/bin/swtpm_patch_swtpm_wrapper
    $ROOT_ESC tee "$wrapper" >/dev/null <<WRAP || return 1
#!/bin/bash
# generated by tpm-provision.sh
args=()
skip_next=false
certificate_type=""
certificate_dir=""
for arg in "\$@"; do
    if \$skip_next; then skip_next=false; continue; fi
    case "\$arg" in
        --tpm-manufacturer|--tpm-model|--tpm-version) skip_next=true; continue ;;
        --tpm-manufacturer=*|--tpm-model=*|--tpm-version=*) continue ;;
        --type=*) certificate_type="\${arg#*=}" ;;
        --dir=*) certificate_dir="\${arg#*=}" ;;
    esac
    args+=("\$arg")
done
for ((i=0; i < \${#args[@]}; i++)); do
    case "\${args[i]}" in
        --type) ((i + 1 < \${#args[@]})) && certificate_type="\${args[i+1]}" ;;
        --dir)  ((i + 1 < \${#args[@]})) && certificate_dir="\${args[i+1]}" ;;
    esac
done
/usr/bin/swtpm_localca "\${args[@]}" \\
    --tpm-manufacturer ${mfr_id} \\
    --tpm-model ${tpm_model} \\
    --tpm-version ${tpm_version} || exit \$?

if [[ "${vendor}" == amd && "\$certificate_type" == ek ]]; then
    ek_certificate="\${certificate_dir%/}/ek.cert"
    if [[ -z "\$certificate_dir" || ! -s "\$ek_certificate" ]]; then
        echo "AMD EK certificate output was not created" >&2
        exit 1
    fi
    exec /usr/bin/python3 ${reissuer_install} \\
        --certificate "\$ek_certificate" \\
        --issuer-certificate /var/lib/swtpm-localca/issuercert.pem \\
        --issuer-key /var/lib/swtpm-localca/signkey.pem \\
        --aia-uri ${aia_uri}
fi
WRAP
    $ROOT_ESC chmod +x "$wrapper" || return 1
    if [[ "$vendor" == amd ]]; then
        $ROOT_ESC grep -Fq -- "--aia-uri ${aia_uri}" "$wrapper" || return 1
    fi

    local board_mfr board_model board_ver
    board_mfr=$($ROOT_ESC dmidecode -s baseboard-manufacturer 2>/dev/null || true)
    board_model=$($ROOT_ESC dmidecode -s baseboard-product-name 2>/dev/null || true)
    board_ver=$($ROOT_ESC dmidecode -s baseboard-version 2>/dev/null || true)
    [[ -n "$board_mfr"   ]] || board_mfr="${vendor^^}"
    [[ -n "$board_model" ]] || board_model="Desktop"
    [[ -n "$board_ver"   ]] || board_ver="1.0"
    $ROOT_ESC tee /etc/swtpm-localca.options >/dev/null <<OPTS || return 1
--platform-manufacturer ${board_mfr}
--platform-version ${board_ver}
--platform-model ${board_model}
OPTS

    local ca_dir=/var/lib/swtpm-localca
    local ca_key="$ca_dir/signkey.pem"
    local ca_certificate="$ca_dir/issuercert.pem"
    local have_ca_key=false have_ca_certificate=false
    $ROOT_ESC mkdir -p "$ca_dir" || return 1
    $ROOT_ESC test -s "$ca_key" && have_ca_key=true
    $ROOT_ESC test -s "$ca_certificate" && have_ca_certificate=true
    if [[ "$have_ca_key" != "$have_ca_certificate" ]]; then
        _tpmp_warn "incomplete SWTPM issuer CA: refusing to replace existing key or certificate"
        return 1
    fi
    if [[ "$have_ca_key" == false ]]; then
        if ! $ROOT_ESC openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 \
                -out "$ca_key" >/dev/null 2>&1 \
           || ! $ROOT_ESC openssl req -new -x509 -key "$ca_key" \
                -out "$ca_certificate" -days 3650 -subj "$ca_subject" \
                -addext "basicConstraints=critical,CA:TRUE" \
                -addext "keyUsage=critical,keyCertSign,cRLSign" \
                -addext "subjectKeyIdentifier=hash" \
                -addext "authorityKeyIdentifier=keyid:always" >/dev/null 2>&1; then
            _tpmp_warn "issuer CA generation failed"
            return 1
        fi
        echo 1 | $ROOT_ESC tee "$ca_dir/certserial" >/dev/null || return 1
        _tpmp_info "EK issuer CA: ${ca_subject#*CN=}"
    fi

    if ! $ROOT_ESC bash -s -- "$ca_certificate" "$ca_key" <<'VALIDATE_CA'
set -euo pipefail
certificate=$1
key=$2
openssl x509 -in "$certificate" -noout -checkend 0 >/dev/null
openssl pkey -in "$key" -noout >/dev/null
certificate_key=$(openssl x509 -in "$certificate" -pubkey -noout | openssl pkey -pubin -outform DER 2>/dev/null | sha256sum | awk '{print $1}')
private_key=$(openssl pkey -in "$key" -pubout -outform DER 2>/dev/null | sha256sum | awk '{print $1}')
[[ -n "$certificate_key" && "$certificate_key" == "$private_key" ]]
openssl x509 -in "$certificate" -noout -text | grep -q 'CA:TRUE'
openssl x509 -in "$certificate" -noout -text | grep -q 'Certificate Sign'
openssl verify -CAfile "$certificate" "$certificate" >/dev/null
VALIDATE_CA
    then
        _tpmp_warn "SWTPM issuer CA is expired, malformed, non-CA, or does not match its key"
        return 1
    fi

    $ROOT_ESC test -f "$ca_dir/certserial" || echo 1 | $ROOT_ESC tee "$ca_dir/certserial" >/dev/null || return 1
    $ROOT_ESC tee /etc/swtpm-localca.conf >/dev/null <<LOCALCACONF || return 1
statedir = ${ca_dir}
signingkey = ${ca_key}
issuercert = ${ca_certificate}
certserial = ${ca_dir}/certserial
LOCALCACONF

    if [[ "$vendor" == amd ]]; then
        local aia_root=/var/lib/swtpm-patch-tpm-aia
        local aia_certificate="${aia_root}${aia_route}"
        local aia_unit=/etc/systemd/system/swtpm-patch-tpm-aia.service
        local aia_gateway persistent_xml live_xml persistent_ips live_ips

        persistent_xml=$($ROOT_ESC virsh -c qemu:///system net-dumpxml default --inactive) || {
            _tpmp_warn "cannot read persistent libvirt default-network XML"
            return 1
        }
        aia_gateway=$(python3 -c '
import ipaddress, sys, xml.etree.ElementTree as ET
root = ET.fromstring(sys.stdin.read())
for node in root.findall("./ip"):
    address = node.get("address", "")
    try:
        if ipaddress.ip_address(address).version == 4:
            print(address)
            break
    except ValueError:
        pass
' <<<"$persistent_xml")
        if [[ -z "$aia_gateway" ]]; then
            _tpmp_warn "default libvirt network has no IPv4 gateway"
            return 1
        fi

        $ROOT_ESC mkdir -p "$(dirname -- "$aia_certificate")" || return 1
        $ROOT_ESC openssl x509 -in "$ca_certificate" -outform DER \
            -out "$aia_certificate" || return 1
        $ROOT_ESC chown root:root "$aia_certificate" || return 1
        $ROOT_ESC chmod 0755 "$aia_root" "$aia_root/pki" "$aia_root/pki/aia" || return 1
        $ROOT_ESC chmod 0444 "$aia_certificate" || return 1

        $ROOT_ESC tee "$aia_unit" >/dev/null <<AIAUNIT || return 1
[Unit]
Description=swtpm AMD TPM CA-Issuers endpoint
Wants=network-online.target
After=network-online.target libvirtd.service virtnetworkd.service

[Service]
Type=simple
DynamicUser=yes
ExecStartPre=/usr/bin/python3 ${aia_server_install} --bind ${aia_gateway} --port ${aia_port} --route ${aia_route} --host ${aia_host} --certificate ${aia_certificate} --check
ExecStart=/usr/bin/python3 ${aia_server_install} --bind ${aia_gateway} --port ${aia_port} --route ${aia_route} --host ${aia_host} --certificate ${aia_certificate}
Restart=always
RestartSec=2s
NoNewPrivileges=yes
CapabilityBoundingSet=
AmbientCapabilities=
PrivateDevices=yes
PrivateTmp=yes
ProtectHome=yes
ProtectSystem=strict
ProtectClock=yes
ProtectHostname=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectProc=invisible
ProcSubset=pid
RestrictAddressFamilies=AF_INET
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
